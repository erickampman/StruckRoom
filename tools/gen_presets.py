#!/usr/bin/env python3
"""gen_presets.py — build-time codegen: turns Presets/*.json into a C++ header the plugin
compiles in directly, so preset selection needs no runtime JSON parser and no filesystem
dependency (no reliance on CLAP's own preset-discovery extension either — this is a plain
in-UI dropdown the plugin manages itself).

Each preset JSON is flattened from its nested {"state": {"parameterState": {module: {item:
"value"}}}} shape into a flat list of ("module.item", float) pairs. The C++ side (StruckRoomUI.cpp)
resolves each plugin parameter to its "module.item" key via the same kPresetKeys table that
PresetDump.hpp uses to *write* these files (see src/UI/PresetKeys.hpp), and looks that key up in
the selected preset's flattened list. Deliberately dumb on this end: this script doesn't need to
know anything about ParamIndex ordering or which keys are current — it just flattens whatever is
in the JSON, so it can't drift out of sync with the C++ param table.

Run by CMake at build time (see CMakeLists.txt); not meant to be run by hand, though it's
harmless to do so.
"""

import argparse
import json
import sys
from pathlib import Path


def flatten_preset(data: dict) -> list[tuple[str, float]]:
    param_state = data.get("state", {}).get("parameterState", {})
    pairs = []
    for module, items in param_state.items():
        if not isinstance(items, dict):
            continue
        for item, value in items.items():
            pairs.append((f"{module}.{item}", float(value)))
    return pairs


def preset_name(data: dict, path: Path) -> str:
    meta_name = data.get("meta", {}).get("name", "")
    if meta_name and meta_name.strip().lower() != "untitled":
        return meta_name
    return path.stem


def emit_header(presets: list[tuple[str, list[tuple[str, float]]]]) -> str:
    lines = [
        "// GeneratedPresets.h — AUTO-GENERATED by tools/gen_presets.py from Presets/*.json.",
        "// Do not edit by hand; edit the source JSON and rebuild instead.",
        "#pragma once",
        "",
        "namespace struckroom {",
        "",
        "struct PresetValue { const char* key; float value; };",
        "struct PresetEntry { const char* name; const PresetValue* values; int count; };",
        "",
    ]

    for i, (name, pairs) in enumerate(presets):
        lines.append(f"static const PresetValue kPresetValues{i}[] = {{")
        for key, value in pairs:
            escaped = key.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'   {{"{escaped}", {value!r}f}},')
        lines.append("};")
        lines.append("")

    lines.append("static const PresetEntry kPresets[] = {")
    for i, (name, pairs) in enumerate(presets):
        escaped_name = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'   {{"{escaped_name}", kPresetValues{i}, {len(pairs)}}},')
    lines.append("};")
    lines.append(f"static const int kPresetCount = {len(presets)};")
    lines.append("")
    lines.append("} // namespace struckroom")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("inputs", nargs="*", help="preset JSON files")
    ap.add_argument("-o", "--output", required=True, help="generated header path")
    args = ap.parse_args()

    presets = []
    for raw_path in args.inputs:
        path = Path(raw_path)
        try:
            data = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError) as e:
            print(f"gen_presets.py: failed to read/parse {path}: {e}", file=sys.stderr)
            return 1
        presets.append((preset_name(data, path), flatten_preset(data)))

    presets.sort(key=lambda p: p[0].lower())

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(emit_header(presets))
    return 0


if __name__ == "__main__":
    sys.exit(main())
